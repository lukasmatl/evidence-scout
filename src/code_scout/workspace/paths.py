"""Canonical paths for workspace-local code-scout state and artifacts."""

from __future__ import annotations

from pathlib import Path

WORKSPACE_STATE_DIRECTORY = ".code-scout"

CONFIG_PATH = f"{WORKSPACE_STATE_DIRECTORY}/config.yaml"
DATABASE_PATH = f"{WORKSPACE_STATE_DIRECTORY}/code-scout.db"
CACHE_DIRECTORY = f"{WORKSPACE_STATE_DIRECTORY}/cache"
LOCK_DIRECTORY = f"{WORKSPACE_STATE_DIRECTORY}/locks"
LOG_DIRECTORY = f"{WORKSPACE_STATE_DIRECTORY}/logs"
TRAJECTORY_DIRECTORY = f"{WORKSPACE_STATE_DIRECTORY}/trajectories"
FASTCONTEXT_TRAJECTORY_DIRECTORY = f"{TRAJECTORY_DIRECTORY}/fastcontext"
CODESCOUT_TRAJECTORY_DIRECTORY = f"{TRAJECTORY_DIRECTORY}/codescout"
VERIFY_TRAJECTORY_DIRECTORY = f"{TRAJECTORY_DIRECTORY}/verify"
GRAPHIFY_OUTPUT_DIRECTORY = f"{WORKSPACE_STATE_DIRECTORY}/graphify-out"
GRAPHIFY_JSON_PATH = f"{GRAPHIFY_OUTPUT_DIRECTORY}/graph.json"
GRAPHIFY_INPUT_PATH = f"{WORKSPACE_STATE_DIRECTORY}/graphify.json"

WORKSPACE_STATE_PATHS = (
    CONFIG_PATH,
    DATABASE_PATH,
    CACHE_DIRECTORY,
    LOCK_DIRECTORY,
    LOG_DIRECTORY,
    TRAJECTORY_DIRECTORY,
    FASTCONTEXT_TRAJECTORY_DIRECTORY,
    CODESCOUT_TRAJECTORY_DIRECTORY,
    VERIFY_TRAJECTORY_DIRECTORY,
    GRAPHIFY_OUTPUT_DIRECTORY,
    GRAPHIFY_JSON_PATH,
    GRAPHIFY_INPUT_PATH,
)


def workspace_state_path(workspace: str | Path, relative_path: str) -> Path:
    """Resolve a canonical state path beneath a workspace root."""
    return Path(workspace) / relative_path


